PATTERNS_MD = r"""# 模式与框架库

## 框架 1：留数算实积分的四步

1. 选围道：有理函数补上半平面大圆弧；三角有理式令 $z=e^{i\theta}$；含 $e^{iax}$ 补上半平面。
2. 找奇点：只要围道内的，边界上的要缩进。
3. 算留数：一阶用极限，$m$ 阶用导数公式，本性奇点展开。
4. 估补路：证明补上的弧或小圆积分趋于零（或趋于某个已知值），否则不能直接等于留数结果。

**判断顺序**：先看被积函数在实轴有没有极点 → 有就缩进取主值；再看大圆弧上是否衰减 → 不衰减就换围道或换方法。

## 框架 2：分离变量五步

1. 齐次化：非齐次边界先用辅助函数搬到零；非齐次方程先单独处理源项。
2. 设乘积解 $u=X(x)T(t)$，代入齐次方程与齐次边界。
3. 分离：两边除以 $XT$，得到"只含 $x$"等于"只含 $t$"，令其为 $-\lambda$。
4. 解本征值问题：由边界条件定 $\lambda_n$、$X_n$；解时间方程得 $T_n$。
5. 叠加并定系数：$u=\sum T_n(t)X_n(x)$，用初始条件与正交性求系数。

**判断顺序**：边界是齐次的吗 → 不是先齐次化；方程是齐次的吗 → 不是先展源项；$\lambda$ 取正还是负 → 看边界能否给出非零解。

## 框架 3：非齐次问题的三招

- **本征函数展开**：源项 $f(x,t)=\sum f_n(t)X_n(x)$，每项解一个受迫常微分方程。
- **冲量定理（杜哈梅）**：零初值受迫解 = $\int_0^t$ 源×自由响应；适合源随时间变化。
- **边界齐次化**：$u=v+w$，$w$ 取线性/多项式满足非齐次边界，$v$ 满足齐次边界。

**选择规则**：源项能展开且边界齐次 → 第一招；初值非零、源任意 → 第二招；边界非齐次 → 先第三招，再回到前两招。

## 框架 4：格林函数构造

1. 写点源方程 $LG=\delta(r-r_0)$。
2. 求自由空间基本解 $G_0$。
3. 加边界修正：镜像法（规则边界）或本征展开（有界区域）。
4. 验算边界条件：$G$ 在边界上必须满足齐次条件。
5. 叠加：$u=\int G f\,dV$（加初始条件的对应项）。

**选择规则**：边界是平面/球面 → 镜像法；边界是矩形/圆柱 → 本征展开；无边界 → 只用基本解。

## 框架 5：特殊函数展开

1. 确认坐标与边界：球 → 勒让德/球谐；柱 → 贝塞尔。
2. 确认边界类型：Dirichlet 用函数零点，Neumann 用导数零点。
3. 写出正交关系与权重（球谐带 $\sin\theta$，贝塞尔带 $r$）。
4. 用正交性算系数，代回级数。
5. 检查有界性：球心丢 $r^{-(l+1)}$，柱轴丢 $Y_\nu$。

## 决策规则

- 区域无界、无边界 → 行波法或傅里叶变换。
- 区域有界、边界是坐标面 → 分离变量。
- 方程有源、要算全场 → 格林函数。
- 只关心 $t>0$ 的初值问题 → 拉普拉斯变换。
- 边界形状复杂但共形映射能化简 → 保角映射 + 拉普拉斯方程。

## 反模式

- **拿到方程就分离变量**：先确认方程与边界是否齐次，否则第一步就错。
- **算留数不估补路**：大圆弧不趋于零时，留数结果不是原积分。
- **把 $\lambda$ 当自由参数**：本征值由边界条件决定，不能任取。
- **格林函数直接用基本解**：不满足边界条件，加多少源都错。
- **特殊函数死记公式**：先想它解决哪个本征方程，公式可以推。
"""

